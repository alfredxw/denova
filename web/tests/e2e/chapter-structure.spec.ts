import { expect, test, type Page } from '../support/fixtures'
import { createAndOpenBook, createProjectFile, getCurrentWorkspace, readProjectFile } from '../support/api'

async function addItem(page: Page, kind: string, title: string) {
  await page.getByRole('button', { name: '新建章节或卷', exact: true }).click()
  await page.getByRole('menuitem', { name: kind, exact: true }).click()
  const dialog = page.getByRole('dialog', { name: kind, exact: true })
  await dialog.getByLabel('标题', { exact: true }).fill(title)
  await dialog.getByRole('button', { name: '创建', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}

test('creates a three-level manuscript, changes it in Book Management and restores its backup', async ({ page, request }, testInfo) => {
  const title = 'Structure E2E Book'
  await page.goto('/')
  const sidebar = page.getByLabel('工作台侧边栏')
  await sidebar.getByRole('button', { name: '书籍管理', exact: true }).click()
  await page.getByRole('button', { name: '新建书籍', exact: true }).click()
  const create = page.getByRole('dialog', { name: '新建书籍' })
  await create.getByPlaceholder('书名（必填）').fill(title)
  await create.getByText('卷 → 章 → 节', { exact: true }).click()
  await create.getByRole('button', { name: '创建', exact: true }).click()
  await expect(create).not.toBeVisible()
  const book = await getCurrentWorkspace(request)
  const summaryURL = `/api/projects/${book.project_id}/book/summary`
  await sidebar.getByRole('button', { name: '写作', exact: true }).click()
  await addItem(page, '新建卷', '远行')
  await expect(page.getByRole('button', { name: /^远行/ })).toBeVisible()
  await addItem(page, '新建章节', '清晨')
  await expect(page.getByRole('button', { name: /^第1章 清晨/ })).toBeVisible()
  await addItem(page, '新建节', '出发')
  const editor = page.locator('.editor-content .ProseMirror').filter({ visible: true })
  await expect(editor).toBeVisible()
  await editor.fill('第一段完整正文。')
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+S' : 'Control+S')
  let summary = (await (await request.get(summaryURL)).json()).summary
  expect(summary.structure).toBe('sections')
  expect(summary.chapters).toHaveLength(1)
  const sectionPath = summary.chapters[0].path
  expect(sectionPath.split('/')).toHaveLength(4)
  await expect.poll(async () => (await readProjectFile(request, book.project_id, sectionPath)).content).toContain('第一段完整正文。')
  await addItem(page, '新建节', '夜色')
  await editor.fill('第二段完整正文。')
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+S' : 'Control+S')
  summary = (await (await request.get(summaryURL)).json()).summary
  await expect.poll(async () => (await readProjectFile(request, book.project_id, summary.chapters[1].path)).content).toContain('第二段完整正文。')
  await page.screenshot({ path: testInfo.outputPath('three-level-outline.png') })

  await sidebar.getByRole('button', { name: '书籍管理', exact: true }).click()
  const card = page.getByRole('group', { name: title, exact: true })
  await card.hover()
  await card.getByRole('button', { name: '调整章节结构', exact: true }).click()
  const change = page.getByRole('dialog', { name: '调整章节结构' })
  await change.getByText('卷 → 章', { exact: true }).click()
  await change.getByRole('button', { name: '预览调整', exact: true }).click()
  await expect(change.getByText('将按阅读顺序合并 1 章的分节，并保留节标题。')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('structure-preview.png') })
  await change.getByRole('button', { name: '备份并应用', exact: true }).click()
  await expect(change).not.toBeVisible()
  summary = (await (await request.get(summaryURL)).json()).summary
  expect(summary.structure).toBe('volumes')
  expect(summary.chapters).toHaveLength(1)
  const merged = (await readProjectFile(request, book.project_id, summary.chapters[0].path)).content
  expect(merged).toContain('第1节 出发')
  expect(merged.indexOf('第一段完整正文。')).toBeLessThan(merged.indexOf('第二段完整正文。'))
  const exported = await request.get(`/api/books/export?path=${encodeURIComponent(book.workspace)}&format=txt`)
  expect(exported.ok()).toBe(true)
  expect(await exported.text()).toContain('第二段完整正文。')
  const history = await (await request.get(`/api/projects/${book.project_id}/versions`)).json()
  const backup = history.versions.find((version: { message: string }) => version.message === '调整章节结构前的备份')
  expect(backup).toBeTruthy()
  const restored = await request.post(`/api/projects/${book.project_id}/versions/${backup.id}/restore`, { data: {} })
  expect(restored.ok(), await restored.text()).toBe(true)
  await page.reload()
  summary = (await (await request.get(summaryURL)).json()).summary
  expect(summary.structure).toBe('sections')
  expect(summary.chapters).toHaveLength(2)
  expect(summary.chapters[0].path).toBe(sectionPath)
})

test('imports and overrides three-level structure with a fresh preview', async ({ page, request }, testInfo) => {
  const settings = await request.patch('/api/settings', { data: { layer: 'user', changes: { theme: 'light' } } })
  expect(settings.ok()).toBe(true)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const sidebar = page.getByLabel('工作台侧边栏')
  // Start navigation at desktop width; inspect the actual dialog at phone width.
  await page.setViewportSize({ width: 1280, height: 850 })
  await sidebar.getByRole('button', { name: '书籍管理', exact: true }).click()
  await page.getByRole('button', { name: '导入现有小说', exact: true }).click()
  await page.locator('input[type=file][accept*=markdown]').setInputFiles({
    name: '结构导入.txt', mimeType: 'text/plain',
    buffer: Buffer.from('第一卷 远行\n第一章 起点\n第一节 清晨\n甲正文。\n第二节 夜色\n乙正文。\n第二章 相遇\n第一节 清晨\n丙正文。'),
  })
  const dialog = page.getByRole('dialog', { name: '导入现有小说' })
  await expect(dialog.getByText('第一卷-远行 / 第一章-起点 / 第一节 清晨', { exact: true })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('import-light-narrow.png') })
  expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await dialog.getByPlaceholder('书名').fill('保留自定义书名')
  await dialog.getByText('章', { exact: true }).click()
  await expect(dialog.getByText('第一章 起点', { exact: true })).toBeVisible()
  await expect(dialog.getByPlaceholder('书名')).toHaveValue('保留自定义书名')
  await dialog.getByText('卷 → 章 → 节', { exact: true }).click()
  await expect(dialog.getByText('第一卷-远行 / 第一章-起点 / 第一节 清晨', { exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '导入', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  const book = await getCurrentWorkspace(request)
  const summary = (await (await request.get(`/api/projects/${book.project_id}/book/summary`)).json()).summary
  expect(summary.structure).toBe('sections')
  expect(summary.chapters).toHaveLength(3)
  const prose = await Promise.all(summary.chapters.map(async (chapter: { path: string }) => (await readProjectFile(request, book.project_id, chapter.path)).content))
  expect(prose.map((text) => /[甲乙丙]正文。/.exec(text)?.[0])).toEqual(['甲正文。', '乙正文。', '丙正文。'])
})

test('changes structure from the manuscript menu after saving the editor draft', async ({ page, request }, testInfo) => {
  const settings = await request.patch('/api/settings', { data: { layer: 'user', changes: { auto_save_enabled: false } } })
  expect(settings.ok()).toBe(true)
  const book = await createAndOpenBook(request, 'Outline Structure Book')
  const originalPath = 'chapters/ch00001-起点.md'
  await createProjectFile(request, book.projectId, originalPath, '原有正文。')
  await page.goto('/')
  await page.getByLabel('工作台侧边栏').getByRole('button', { name: '写作', exact: true }).click()
  await page.getByRole('button', { name: /^起点/ }).click()
  const editor = page.locator('.editor-content .ProseMirror').filter({ visible: true })
  await editor.fill('尚未手动保存的最新正文。')
  expect((await readProjectFile(request, book.projectId, originalPath)).content).toBe('原有正文。')
  const menu = page.getByRole('button', { name: '正文目录操作', exact: true })
  await menu.click()
  await expect(page.getByRole('menuitem', { name: '调整章节结构', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('outline-structure-menu.png'), animations: 'disabled' })
  await page.getByRole('menuitem', { name: '调整章节结构', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '调整章节结构', exact: true })
  await dialog.getByRole('radio', { name: '卷 → 章 → 节', exact: true }).click()
  await dialog.getByRole('button', { name: '预览调整', exact: true }).click()
  await expect(dialog.getByText('已有章节的正文会完整放入第一节。')).toBeVisible()
  expect((await readProjectFile(request, book.projectId, originalPath)).content).toContain('尚未手动保存的最新正文。')
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  const summaryURL = `/api/projects/${book.projectId}/book/summary`
  expect((await (await request.get(summaryURL)).json()).summary.structure).toBe('chapters')

  await menu.click()
  await page.getByRole('menuitem', { name: '调整章节结构', exact: true }).click()
  await dialog.getByRole('radio', { name: '卷 → 章 → 节', exact: true }).click()
  await dialog.getByRole('button', { name: '预览调整', exact: true }).click()
  await dialog.getByRole('button', { name: '备份并应用', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(menu).toBeVisible()
  await page.getByRole('button', { name: /^第一节/ }).click()
  await expect(editor).toContainText('尚未手动保存的最新正文。')
  await editor.fill('调整结构后继续创作。')
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+S' : 'Control+S')
  const summary = (await (await request.get(summaryURL)).json()).summary
  expect(summary.structure).toBe('sections')
  expect(summary.chapters).toHaveLength(1)
  await expect.poll(async () => (await readProjectFile(request, book.projectId, summary.chapters[0].path)).content).toContain('调整结构后继续创作。')
  const history = await (await request.get(`/api/projects/${book.projectId}/versions`)).json()
  expect(history.versions.some((version: { message: string }) => version.message === '调整章节结构前的备份')).toBe(true)
  await page.getByRole('button', { name: '新建章节或卷', exact: true }).click()
  await expect(page.getByRole('menuitem', { name: '新建节', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('outline-create-dark.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
})

