async function createSource(request: APIRequestContext, fixture: string, id: string) {
  const response = await request.post('/api/agent-chat/projects/directory', { data: { name: id } })
  expect(response.ok(), await response.text()).toBe(true)
  const project = await response.json()
  const index = await (await request.get('/api/agent-chat/projects')).json()
  const directory = index.projects.find((item: { id: string }) => item.id === project.id).path
  for (const source of ['runtime', fixture]) {
    const fixtureDirectory = new URL('../../../internal/platform/testdata/' + source + '/', import.meta.url)
    for (const entry of await readdir(fixtureDirectory)) {
      await cp(new URL(entry, fixtureDirectory), path.join(directory, entry), { recursive: true, force: false, errorOnExist: true })
    }
  }
  const manifestPath = path.join(directory, fixture === 'tool' ? 'denova.plugin.json' : 'denova.game.json')
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
  manifest.id = id
  manifest.name = { 'zh-CN': id, 'en-US': id }
  await writeFile(manifestPath, JSON.stringify(manifest))
  const sources = await (await request.get('/api/platform/manage/development')).json()
  const development = sources.find((source: { projectId: string }) => source.projectId === project.id)
  expect(development).toBeDefined()
  return { project, development }
}

async function installSource(request: APIRequestContext, fixture: string, id: string) {
  const source = await createSource(request, fixture, id)
  const checked = await request.get(`/api/platform/manage/development/${source.development.developmentId}/check`)
  expect(checked.ok(), await checked.text()).toBe(true)
  const candidate = await checked.json()
  const installed = await request.post('/api/platform/manage/packages/install', { data: { candidateId: candidate.candidateId, grants: candidate.manifest.permissions.required } })
  expect(installed.ok(), await installed.text()).toBe(true)
  return installed.json()
}

